"""Generate the shared 64-bit test vectors from independent integer arithmetic.

Run: python Simulation/TestVectors/generate_adder_vectors.py
The generated file is Simulation/Adder00.tvs, used by both testbenches.
"""
from pathlib import Path
from random import Random

N = 64
MASK = (1 << N) - 1
SIGN = 1 << (N - 1)


def expected_result(a, b, cin):
    total = a + b + cin
    signed_a = a - (1 << N) if a & SIGN else a
    signed_b = b - (1 << N) if b & SIGN else b
    signed_total = signed_a + signed_b + cin
    return total & MASK, total >> N, int(not -SIGN <= signed_total < SIGN)


def main():
    cases = []
    seed_file = Path(__file__).with_name("Adder00.tvs.txt")
    for line_number, line in enumerate(seed_file.read_text().splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("--"):
            continue
        a, b, cin, s, cout, ovfl = line.split()
        inputs = int(a, 16), int(b, 16), int(cin)
        expected = int(s, 16), int(cout), int(ovfl)
        if expected_result(*inputs) != expected:
            raise ValueError(f"Incorrect expected result at {seed_file}:{line_number}")
        cases.append(inputs)

    # Exercise each sum bit high and low, with known reference vectors between.
    for bit in range(N):
        one = 1 << bit
        cases.extend([(0, 0, 0), (one, 0, 0), (0, 0, 0),
                      (MASK ^ one, 0, 0), (MASK, 0, 0)])

    # Carry chains of every length, generated by B or by the external carry-in.
    for length in range(1, N + 1):
        low_ones = (1 << length) - 1
        cases.extend([(low_ones, 1, 0), (low_ones, 0, 1)])

    # All eight (A_bit, B_bit, carry_in) combinations at every bit position.
    for bit in range(N):
        for a_bit in range(2):
            for b_bit in range(2):
                for carry in range(2):
                    low = (1 << bit) - 1 if carry else 0
                    cases.append(((a_bit << bit) | low, b_bit << bit, carry))

    # Positive/negative overflow, unsigned carry, and ordinary sign combinations.
    for a, b, cin in [(SIGN - 1, 1, 0), (SIGN - 1, 0, 1),
                      (SIGN, SIGN, 0), (SIGN, MASK, 0),
                      (MASK, 1, 0), (SIGN, SIGN - 1, 0)]:
        cases.extend([(a, b, cin), (0, 0, 0)])

    rng = Random(350)
    cases.extend((rng.getrandbits(N), rng.getrandbits(N), rng.randrange(2))
                 for _ in range(256))

    lines = [
        "-- Generated by TestVectors/generate_adder_vectors.py; do not edit.",
        "-- A (16 hex) B (16 hex) Cin (binary) S (16 hex) Cout Ovfl (binary)",
        f"-- {len(cases)} directed and repeatable random measurements.",
    ]
    for a, b, cin in cases:
        s, cout, ovfl = expected_result(a, b, cin)
        lines.append(f"{a:016X} {b:016X} {cin} {s:016X} {cout} {ovfl}")

    target = Path(__file__).resolve().parent.parent / "Adder00.tvs"
    target.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"Wrote {len(cases)} vectors to {target}")


if __name__ == "__main__":
    main()
